enum class TechCategory(val title: String, val badge: String) {
    MILITARY_UNIT("Askeri Birim", "⚔️"),
    MILITARY_STRUCTURE("Savunma & Üretim Tesisi", "🏗️"),
    STRATEGIC_BUFF("Stratejik & Pasif Doktrin", "🛡️"),
    ERA_GATE("Çağ Atlama Eşiği", "👑")
}

data class TechNode(
    val id: String,
    val name: String,
    val era: Era,
    val category: TechCategory,
    val costTechPoints: Int,
    val costGold: Int,
    val costIron: Int,
    val durationSeconds: Int,
    val description: String,
    val iconEmoji: String,
    val unlocksUnitName: String? = null,
    val unlocksUnitType: UnitType? = null,
    val unlocksStructureTitle: String? = null,
    val passiveBonusText: String? = null,
    val prerequisiteTechId: String? = null,
    var isResearched: Boolean = false,
    var isResearching: Boolean = false,
    var progressPercent: Float = 0f,
    var timeRemaining: Float = 0f
) {
    val isAvailableToResearch: Boolean
        get() = !isResearched && !isResearching
}

